-- 1.6.0: gestão de patrimônio. A etiqueta passa a ter local, responsável e situação, com baixa.
--
-- Unidades (ex.: Matriz, Filial SP) agrupam os locais (Sala 101, Almoxarifado). Nome único sem diferenciar maiúsculas.
create table unidades (
    id         bigint generated by default as identity primary key,
    nome       varchar(120) not null,
    ativa      boolean      not null default true,
    criada_em  timestamp    not null default now()
);
create unique index uk_unidades_nome on unidades (lower(nome));

-- O local (criado pelo coletor no inventário ou na web) ganha a unidade e pode ser desativado. Sem unidade = os
-- locais de antes e os criados pelo coletor com um nome novo (a tela Locais mostra em "Sem unidade").
alter table locais add column unidade_id bigint references unidades (id);
alter table locais add column ativo boolean not null default true;
create index idx_locais_unidade on locais (unidade_id);

-- Responsáveis pelos bens: pessoas sem login no sistema (o termo de responsabilidade sai em nome delas).
create table responsaveis (
    id         bigint generated by default as identity primary key,
    nome       varchar(160) not null,
    setor      varchar(120),
    matricula  varchar(60),
    email      varchar(160),
    ativo      boolean      not null default true,
    criado_em  timestamp    not null default now()
);
create unique index uk_responsaveis_matricula on responsaveis (lower(matricula)) where matricula is not null;

-- O bem: local e responsável atuais, situação e os dados da baixa (o bem baixado continua no cadastro e no histórico).
-- Situação: EM_USO, EM_ESTOQUE, EM_MANUTENCAO, EMPRESTADO, EXTRAVIADO, BAIXADO.
alter table tags add column local_id bigint references locais (id);
alter table tags add column responsavel_id bigint references responsaveis (id);
alter table tags add column situacao varchar(20) not null default 'EM_USO';
alter table tags add column baixa_motivo varchar(20);
alter table tags add column baixa_em date;
alter table tags add column baixa_observacao varchar(500);
alter table tags add column baixa_por varchar(255);
create index idx_tags_local on tags (local_id);
create index idx_tags_responsavel on tags (responsavel_id);
create index idx_tags_situacao on tags (situacao);
