-- Versões do app Android publicadas pelo servidor (tela "App dos coletores"). O APK fica em arquivo
-- (rfid.app.pasta, padrão ./data/app); aqui ficam os dados conferidos no envio. Só as últimas versões
-- guardam o arquivo (rfid.app.versoes-guardadas): as mais antigas ficam no histórico com arquivo_removido.
create table versoes_app (
    id                 bigint generated by default as identity primary key,
    versao_nome        varchar(50)   not null,
    codigo             integer       not null,
    arquivo            varchar(255)  not null,
    tamanho            bigint        not null,
    sha256             varchar(64)   not null,
    certificado_sha256 varchar(64)   not null,
    notas              varchar(1000),
    publicada_em       timestamp     not null,
    publicada_por      varchar(255)  not null,
    arquivo_removido   boolean       default false not null,
    constraint uk_versoes_app_codigo unique (codigo)
);
