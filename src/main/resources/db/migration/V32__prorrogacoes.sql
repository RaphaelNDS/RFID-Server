-- 1.16.0: prorrogação do pedido de locação. Cada mudança da devolução prevista fica registrada com a data de antes,
-- a nova, o motivo e quem mudou (o contrato e a tela do pedido mostram o histórico).
create table pedido_prorrogacoes (
    id             bigint generated by default as identity primary key,
    pedido_id      bigint       not null references pedidos_locacao (id),
    data_anterior  date         not null,
    data_nova      date         not null,
    motivo         varchar(500) not null,
    registrada_por varchar(255) not null,
    criada_em      timestamp    not null default now()
);
create index idx_pedido_prorrogacoes_pedido on pedido_prorrogacoes (pedido_id, id);
