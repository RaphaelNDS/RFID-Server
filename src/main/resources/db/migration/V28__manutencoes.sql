-- 1.11.0: manutenção do bem (ordem de serviço numerada; o número é o id).
--
-- Uma ordem por bem: o bem sai "Em manutenção" e volta para a situação anterior quando a ordem é concluída ou
-- cancelada. Guarda o bem pelo nome no momento (a ordem continua legível se a etiqueta for excluída depois).
create table manutencoes (
    id                  bigint generated by default as identity primary key,
    tag_id              bigint        references tags (id) on delete set null,
    tag_real            varchar(255)  not null,
    patrimonio          varchar(255),
    descricao_bem       varchar(255),
    tipo                varchar(20)   not null,
    problema            varchar(500)  not null,
    fornecedor          varchar(160),
    data_envio          date          not null,
    previsao_retorno    date,
    situacao_anterior   varchar(20)   not null,
    status              varchar(20)   not null,
    concluida_em        date,
    servico_realizado   varchar(500),
    custo               numeric(14, 2),
    resultado           varchar(20),
    registrada_por      varchar(255)  not null,
    concluida_por       varchar(255),
    criada_em           timestamp     not null default now(),
    constraint ck_manutencoes_tipo check (tipo in ('PREVENTIVA', 'CORRETIVA')),
    constraint ck_manutencoes_status check (status in ('ABERTA', 'CONCLUIDA', 'CANCELADA')),
    constraint ck_manutencoes_resultado check (resultado is null or resultado in ('CONSERTADO', 'SEM_CONSERTO')),
    constraint ck_manutencoes_custo check (custo is null or custo >= 0),
    constraint ck_manutencoes_previsao check (previsao_retorno is null or previsao_retorno >= data_envio)
);
create index idx_manutencoes_envio on manutencoes (data_envio desc, id desc);
create index idx_manutencoes_tag on manutencoes (tag_id);
create index idx_manutencoes_tag_real on manutencoes (tag_real);
-- Um bem só pode ter uma manutenção aberta por vez
create unique index ux_manutencoes_aberta on manutencoes (tag_id) where status = 'ABERTA' and tag_id is not null;
