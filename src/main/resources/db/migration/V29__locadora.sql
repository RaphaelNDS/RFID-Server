-- 1.12.0: o sistema passa a ser de LOCADORA. Os equipamentos são alugados a clientes por pedido de locação,
-- vendidos ou voltam do aluguel. O "empréstimo para responsável" da 1.10.0 vira o pedido de locação.

-- Clientes da locadora. origem_responsavel_id: o responsável da 1.10.0 de onde o cliente veio na conversão abaixo.
create table clientes (
    id                     bigint generated by default as identity primary key,
    nome                   varchar(160) not null,
    documento              varchar(20),
    contato                varchar(160),
    telefone               varchar(40),
    email                  varchar(160),
    endereco               varchar(300),
    observacao             varchar(500),
    ativo                  boolean      not null default true,
    criado_em              timestamp    not null default now(),
    origem_responsavel_id  bigint
);
create unique index ux_clientes_documento on clientes (documento) where documento is not null;
create index idx_clientes_nome on clientes (lower(nome));

-- Pedido de locação (o número é o id). situacao: ABERTO (nada saiu), EM_SEPARACAO (saiu parte), ENTREGUE (saiu
-- tudo), DEVOLVIDO_PARCIAL, ENCERRADO (tudo voltou) ou CANCELADO. separacao_concluida: todas as vagas foram
-- preenchidas, ou a web encerrou a separação com o que saiu.
create table pedidos_locacao (
    id                    bigint generated by default as identity primary key,
    cliente_id            bigint       not null references clientes (id),
    cliente               varchar(255) not null,
    saida_prevista        date,
    previsao_devolucao    date         not null,
    local_entrega         varchar(300),
    observacao            varchar(500),
    situacao              varchar(20)  not null,
    separacao_concluida   boolean      not null default false,
    cancelamento_motivo   varchar(500),
    registrado_por        varchar(255) not null,
    criado_em             timestamp    not null default now(),
    constraint ck_pedidos_situacao check (situacao in ('ABERTO', 'EM_SEPARACAO', 'ENTREGUE', 'DEVOLVIDO_PARCIAL', 'ENCERRADO', 'CANCELADO'))
);
create index idx_pedidos_situacao on pedidos_locacao (situacao, previsao_devolucao);
create index idx_pedidos_cliente on pedidos_locacao (cliente_id);

-- O que o pedido pede: N unidades de um tipo (marca e modelo opcionais: qualquer um serve) ou um bem específico.
create table pedido_linhas (
    id                    bigint generated by default as identity primary key,
    pedido_id             bigint       not null references pedidos_locacao (id),
    especifico            boolean      not null default false,
    tag_id                bigint       references tags (id) on delete set null,
    tipo_equipamento_id   bigint       references tipo_equipamento (id),
    marca_id              bigint       references marca (id),
    modelo_id             bigint       references modelo (id),
    descricao             varchar(255) not null,
    quantidade            integer      not null,
    constraint ck_pedido_linhas_quantidade check (quantidade between 1 and 1000),
    constraint ck_pedido_linhas_tipo check (especifico or tipo_equipamento_id is not null)
);
create index idx_pedido_linhas_pedido on pedido_linhas (pedido_id);

-- Os equipamentos que saíram, com a devolução (pelo coletor ou pela web) e a conferência dela (estado: OK, AVARIA ou
-- FALTANDO_ACESSORIO; a conferência manda o bem para Disponível ou abre a manutenção).
create table pedido_itens (
    id                    bigint generated by default as identity primary key,
    pedido_id             bigint       not null references pedidos_locacao (id),
    linha_id              bigint       not null references pedido_linhas (id),
    tag_id                bigint       references tags (id) on delete set null,
    tag_real              varchar(255) not null,
    patrimonio            varchar(255),
    descricao             varchar(255),
    saida_em              timestamp    not null,
    saida_por             varchar(255) not null,
    devolvido_em          timestamp,
    devolvido_por         varchar(255),
    conferido_em          timestamp,
    conferido_por         varchar(255),
    estado_devolucao      varchar(20),
    observacao_devolucao  varchar(500),
    manutencao_id         bigint       references manutencoes (id),
    constraint ck_pedido_itens_estado check (estado_devolucao is null or estado_devolucao in ('OK', 'AVARIA', 'FALTANDO_ACESSORIO'))
);
create index idx_pedido_itens_pedido on pedido_itens (pedido_id);
create index idx_pedido_itens_tag_real on pedido_itens (tag_real);
-- Um equipamento só está em um pedido por vez: do momento da saída até a conferência da devolução
create unique index ux_pedido_itens_em_aberto on pedido_itens (tag_id) where conferido_em is null and tag_id is not null;

-- Venda do equipamento: ele fica Vendido (sai do acervo). desfeita_em: a venda foi lançada por engano.
create table vendas (
    id              bigint generated by default as identity primary key,
    tag_id          bigint        references tags (id) on delete set null,
    tag_real        varchar(255)  not null,
    patrimonio      varchar(255),
    descricao       varchar(255),
    cliente_id      bigint        references clientes (id),
    cliente         varchar(255),
    valor           numeric(14, 2),
    data            date          not null,
    observacao      varchar(500),
    registrada_por  varchar(255)  not null,
    criada_em       timestamp     not null default now(),
    desfeita_em     timestamp,
    desfeita_por    varchar(255),
    constraint ck_vendas_valor check (valor is null or valor >= 0)
);
create index idx_vendas_tag on vendas (tag_id);

-- ===== Conversão dos empréstimos da 1.10.0 em pedidos de locação (mesmo número) =====

insert into clientes (nome, contato, email, origem_responsavel_id)
select r.nome, nullif(trim(concat_ws(', ', r.setor, case when r.matricula is not null then 'mat. ' || r.matricula end)), ''), r.email, r.id
from responsaveis r
where r.id in (select distinct responsavel_id from emprestimos);

insert into pedidos_locacao (id, cliente_id, cliente, saida_prevista, previsao_devolucao, observacao, situacao,
                             separacao_concluida, registrado_por, criado_em)
select e.id, c.id, e.responsavel, e.data_saida, e.previsao_devolucao, e.finalidade,
       case
           when not exists (select 1 from emprestimo_itens i where i.emprestimo_id = e.id and i.devolvido_em is null) then 'ENCERRADO'
           when exists (select 1 from emprestimo_itens i where i.emprestimo_id = e.id and i.devolvido_em is not null) then 'DEVOLVIDO_PARCIAL'
           else 'ENTREGUE'
       end,
       true, e.registrado_por, e.criado_em
from emprestimos e
join clientes c on c.origem_responsavel_id = e.responsavel_id;

-- Uma linha "bem específico" por bem emprestado, com o mesmo id do item (o item abaixo aponta para ela)
insert into pedido_linhas (id, pedido_id, especifico, tag_id, descricao, quantidade)
select i.id, i.emprestimo_id, true, i.tag_id, coalesce(i.patrimonio, i.tag_real) || coalesce(' · ' || i.descricao, ''), 1
from emprestimo_itens i;

-- Devolvido no empréstimo = devolvido e conferido (a situação do bem já tinha voltado)
insert into pedido_itens (id, pedido_id, linha_id, tag_id, tag_real, patrimonio, descricao, saida_em, saida_por,
                          devolvido_em, devolvido_por, conferido_em, conferido_por, estado_devolucao, observacao_devolucao)
select i.id, i.emprestimo_id, i.id, i.tag_id, i.tag_real, i.patrimonio, i.descricao, e.data_saida::timestamp, e.registrado_por,
       i.devolvido_em::timestamp, i.devolvido_por, i.devolvido_em::timestamp, i.devolvido_por,
       case when i.devolvido_em is not null then 'OK' end, i.condicao_devolucao
from emprestimo_itens i
join emprestimos e on e.id = i.emprestimo_id;

-- Os próximos números continuam depois dos convertidos
select setval(pg_get_serial_sequence('pedidos_locacao', 'id'), coalesce((select max(id) from pedidos_locacao), 0) + 1, false);
select setval(pg_get_serial_sequence('pedido_linhas', 'id'), coalesce((select max(id) from pedido_linhas), 0) + 1, false);
select setval(pg_get_serial_sequence('pedido_itens', 'id'), coalesce((select max(id) from pedido_itens), 0) + 1, false);

