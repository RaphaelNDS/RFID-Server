-- Inventário por local: o coletor abre um inventário num local, lê as etiquetas e finaliza.
-- Não há lista esperada por local: o inventário registra o que foi lido em cada local.

-- Nomes de locais já usados, para o app sugerir em vez de cada operador digitar de um jeito.
-- A unicidade sem diferenciar maiúsculas é garantida no InventarioService.
create table locais (
    id        bigint generated by default as identity primary key,
    nome      varchar(120) not null,
    criado_em timestamp    not null,
    constraint uk_locais_nome unique (nome)
);

-- O id é um UUID gerado no coletor: o inventário pode ser aberto offline e enviado depois,
-- e reenviar o mesmo inventário não cria duplicado.
create table inventarios (
    id            varchar(36)  primary key,
    local_id      bigint       not null,
    dispositivo   varchar(100) not null,
    status        varchar(20)  not null,
    iniciado_em   timestamp    not null,
    finalizado_em timestamp,
    recebido_em   timestamp    not null,
    constraint fk_inventarios_local foreign key (local_id) references locais (id)
);

create index idx_inventarios_iniciado_em on inventarios (iniciado_em);

-- Cada etiqueta lida no inventário (uma vez por inventário). Os dados da etiqueta são copiados
-- no recebimento: o relatório continua igual mesmo se o cadastro mudar depois.
create table inventario_itens (
    id             bigint generated by default as identity primary key,
    inventario_id  varchar(36)  not null,
    tag            varchar(255) not null,
    lido_em        timestamp    not null,
    cadastrada     boolean      not null,
    codigo_interno varchar(255),
    patrimonio     varchar(255),
    tipo           varchar(255),
    marca          varchar(255),
    modelo         varchar(255),
    constraint fk_inventario_itens_inventario foreign key (inventario_id) references inventarios (id),
    constraint uk_inventario_itens_tag unique (inventario_id, tag)
);
