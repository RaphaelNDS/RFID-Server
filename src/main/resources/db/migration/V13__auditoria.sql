-- Auditoria de usuários e configurações: quem fez o quê, quando e por onde. Antes isso ficava só no log, que
-- guarda 30 dias. Mesmo modelo do histórico de etiquetas (V9): somente leitura, nenhuma tela altera ou apaga,
-- fora de qualquer retenção. Sem chave estrangeira: o registro continua se o usuário ou o item for excluído.
create table auditoria (
    id       bigint generated by default as identity primary key,
    momento  timestamp     not null,
    usuario  varchar(255)  not null,
    origem   varchar(120)  not null,
    area     varchar(30)   not null,
    acao     varchar(80)   not null,
    alvo     varchar(255),
    detalhe  varchar(1000)
);

create index idx_auditoria_momento on auditoria (momento);
create index idx_auditoria_area on auditoria (area, momento);
