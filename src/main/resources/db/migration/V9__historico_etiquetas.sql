-- Histórico do cadastro de etiquetas: quem cadastrou, alterou ou excluiu, quando, por onde (web ou coletor),
-- campo, valor antigo e valor novo. Somente leitura (nenhuma tela altera ou apaga) e fora de qualquer retenção.
-- Sem chave estrangeira para tags: o histórico de uma etiqueta excluída continua (tag_real e o id antigo).
-- Tipo, marca e modelo vão pelo NOME: se o catálogo mudar depois, o histórico continua legível.
create table historico_etiquetas (
    id           bigint generated by default as identity primary key,
    tag_id       bigint,
    tag_real     varchar(255) not null,
    acao         varchar(20)  not null,
    campo        varchar(50),
    valor_antigo varchar(500),
    valor_novo   varchar(500),
    usuario      varchar(255) not null,
    origem       varchar(120) not null,
    momento      timestamp    not null
);

create index idx_historico_etiquetas_tag on historico_etiquetas (tag_real, momento);
create index idx_historico_etiquetas_momento on historico_etiquetas (momento);
