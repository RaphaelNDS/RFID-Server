-- 1.22.0: campos personalizados por tipo de equipamento (ex.: voltagem e versão de firmware no PDV). Cada tipo tem os
-- seus campos; o valor de cada equipamento fica em valores_campo. Desativar um campo esconde, sem apagar os valores.
create table campos_tipo (
    id                   bigint generated by default as identity primary key,
    tipo_equipamento_id  bigint       not null references tipo_equipamento (id) on delete cascade,
    nome                 varchar(80)  not null,
    formato              varchar(20)  not null,
    opcoes               varchar(1000),
    obrigatorio          boolean      not null default false,
    ordem                integer      not null default 0,
    ativo                boolean      not null default true,
    criado_em            timestamp    not null default now(),
    constraint ck_campos_tipo_formato check (formato in ('TEXTO', 'NUMERO', 'DATA', 'LISTA', 'SIM_NAO')),
    constraint ck_campos_tipo_lista check (formato <> 'LISTA' or opcoes is not null)
);
create unique index ux_campos_tipo_nome on campos_tipo (tipo_equipamento_id, lower(nome));

create table valores_campo (
    id        bigint generated by default as identity primary key,
    tag_id    bigint       not null references tags (id) on delete cascade,
    campo_id  bigint       not null references campos_tipo (id) on delete cascade,
    valor     varchar(500) not null
);
create unique index ux_valores_campo on valores_campo (tag_id, campo_id);
create index idx_valores_campo_valor on valores_campo (lower(valor));
