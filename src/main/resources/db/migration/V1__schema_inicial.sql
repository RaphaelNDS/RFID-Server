-- Schema inicial do RFID Server (equivalente ao que o Hibernate gerava com ddl-auto).
-- A partir daqui, toda mudança de tabela deve virar uma nova migração (V2__..., V3__...).
-- Os enums (role, modulo, acao) ficam sem CHECK para que adicionar um valor novo no Kotlin
-- não quebre os inserts por esquecimento de migração.

create table tipo_equipamento (
    id   bigint generated by default as identity primary key,
    nome varchar(255) not null,
    constraint uk_tipo_equipamento_nome unique (nome)
);

create table marca (
    id      bigint generated by default as identity primary key,
    tipo_id bigint       not null,
    nome    varchar(255) not null,
    constraint fk_marca_tipo foreign key (tipo_id) references tipo_equipamento (id)
);

create table modelo (
    id       bigint generated by default as identity primary key,
    marca_id bigint       not null,
    nome     varchar(255) not null,
    constraint fk_modelo_marca foreign key (marca_id) references marca (id)
);

create table tags (
    id                  bigint generated by default as identity primary key,
    tipo_equipamento_id bigint,
    marca_id            bigint,
    modelo_id           bigint,
    codigo_interno      varchar(255) not null,
    numero_serie        varchar(255),
    patrimonio          varchar(255),
    tag_hash            varchar(255) not null,
    tag_real            varchar(255) not null,
    constraint uk_tags_tag_hash unique (tag_hash),
    constraint uk_tags_tag_real unique (tag_real)
);

create index idx_tags_patrimonio on tags (patrimonio);

create table tags_nao_cadastradas (
    id        bigint generated by default as identity primary key,
    tag       varchar(255) not null,
    data_hora timestamp(6) not null,
    constraint uk_tags_nao_cadastradas_tag unique (tag)
);

create table leituras_android (
    id             bigint generated by default as identity primary key,
    tag            varchar(255),
    codigo_interno varchar(255),
    tipo           varchar(255),
    marca          varchar(255),
    modelo         varchar(255),
    patrimonio     varchar(255),
    numero_serie   varchar(255),
    data_hora      timestamp(6)
);

-- Dashboard e tela de leituras filtram por data
create index idx_leituras_android_data_hora on leituras_android (data_hora);

create table usuarios (
    id    bigint generated by default as identity primary key,
    nome  varchar(255),
    email varchar(255),
    senha varchar(255),
    role  varchar(255),
    constraint uk_usuarios_email unique (email)
);

create table permissoes (
    id         bigint generated by default as identity primary key,
    usuario_id bigint,
    modulo     varchar(255),
    acao       varchar(255),
    constraint fk_permissoes_usuario foreign key (usuario_id) references usuarios (id)
);
