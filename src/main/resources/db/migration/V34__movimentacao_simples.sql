-- ===== Movimentações =====

-- Uma saída ou entrada, com número (o id). destino: para onde foi (texto livre, obrigatório na saída).
-- registrado_por: o email de quem registrou na web ou o operador do coletor. origem: WEB ou COLETOR.
create table movimentos (
    id              bigint generated by default as identity primary key,
    tipo            varchar(10)  not null,
    data_hora       timestamp    not null,
    destino         varchar(255),
    observacao      varchar(500),
    registrado_por  varchar(255) not null,
    origem          varchar(10)  not null,
    criado_em       timestamp    not null default now(),
    constraint ck_movimentos_tipo check (tipo in ('SAIDA', 'ENTRADA')),
    constraint ck_movimentos_origem check (origem in ('WEB', 'COLETOR')),
    constraint ck_movimentos_destino check (tipo <> 'SAIDA' or (destino is not null and length(trim(destino)) > 0))
);
create index idx_movimentos_data on movimentos (data_hora desc, id desc);

-- Os equipamentos da movimentação, com o EPC, o patrimônio e a descrição no momento. A etiqueta excluída depois
-- continua no comprovante (tag_id vira nulo).
create table movimento_itens (
    id            bigint generated by default as identity primary key,
    movimento_id  bigint       not null references movimentos (id),
    tag_id        bigint       references tags (id) on delete set null,
    tag_real      varchar(255) not null,
    patrimonio    varchar(255),
    descricao     varchar(255)
);
create index idx_movimento_itens_movimento on movimento_itens (movimento_id);
create index idx_movimento_itens_tag on movimento_itens (tag_id);
create index idx_movimento_itens_tag_real on movimento_itens (tag_real);

-- ===== Situações do equipamento: DISPONIVEL (No estoque), FORA (Fora do estoque), EXTRAVIADO, BAIXADO =====

-- Cada conversão fica no histórico da etiqueta (mesmo formato das alterações feitas pela tela)
insert into historico_etiquetas (tag_id, tag_real, acao, campo, valor_antigo, valor_novo, usuario, origem, momento)
select t.id, t.tag_real, 'ALTERACAO', 'Situação',
       case t.situacao
           when 'ALUGADO' then 'Alugado' when 'EM_DEVOLUCAO' then 'Em devolução' when 'EM_MANUTENCAO' then 'Em manutenção'
           when 'A_VENDA' then 'À venda' when 'VENDIDO' then 'Vendido' when 'EMPRESTADO' then 'Emprestado'
           when 'EM_USO' then 'Em uso' when 'EM_ESTOQUE' then 'Em estoque' else t.situacao
       end,
       case
           when t.situacao in ('ALUGADO', 'EM_DEVOLUCAO', 'EM_MANUTENCAO', 'EMPRESTADO') then 'Fora do estoque'
           when t.situacao = 'VENDIDO' then 'Baixado'
           else 'No estoque'
       end,
       'sistema', 'Atualização 2.0.0 (V34)', now()
from tags t
where t.situacao not in ('DISPONIVEL', 'FORA', 'EXTRAVIADO', 'BAIXADO');

-- Com o cliente, esperando a conferência da devolução ou em manutenção: fora do estoque
update tags set situacao = 'FORA' where situacao in ('ALUGADO', 'EM_DEVOLUCAO', 'EM_MANUTENCAO', 'EMPRESTADO');
-- Vendido: baixado com o motivo Venda (data da venda, se houver; senão a de hoje)
update tags t
set situacao = 'BAIXADO',
    baixa_motivo = coalesce(t.baixa_motivo, 'VENDA'),
    baixa_em = coalesce(t.baixa_em,
                        (select max(v.data) from vendas v where v.tag_id = t.id and v.desfeita_em is null),
                        current_date),
    baixa_observacao = coalesce(t.baixa_observacao, 'Vendido (convertido na atualização 2.0.0)'),
    baixa_por = coalesce(t.baixa_por, 'sistema')
where t.situacao = 'VENDIDO';
-- À venda e os nomes de antes da 1.12.0 (em uso, em estoque): no estoque
update tags set situacao = 'DISPONIVEL' where situacao not in ('DISPONIVEL', 'FORA', 'EXTRAVIADO', 'BAIXADO');

alter table tags add constraint ck_tags_situacao check (situacao in ('DISPONIVEL', 'FORA', 'EXTRAVIADO', 'BAIXADO'));

-- ===== Usuários e permissões =====

-- Perfis de função da versão de locação (Expedição, Conferente, Técnico): viram Personalizado, com as permissões que
-- já tinham (as de locação e manutenção viram as de Movimentações logo abaixo)
update usuarios set role = 'CUSTOM' where role in ('EXPEDICAO', 'CONFERENTE', 'TECNICO');

-- Quem tinha Locação ou Manutenção (levar o equipamento para fora e trazer de volta) passa a ter Movimentações com
-- a mesma ação
insert into permissoes (usuario_id, modulo, acao)
select distinct p.usuario_id, 'MOVIMENTO', p.acao
from permissoes p
where p.modulo in ('LOCACAO', 'MANUTENCAO')
  and not exists (select 1 from permissoes q where q.usuario_id = p.usuario_id and q.modulo = 'MOVIMENTO' and q.acao = p.acao);

-- Os perfis prontos ganham Movimentações como os outros módulos: Administrador tudo, Gestor ver/criar/editar,
-- Usuário só ver (UserService.permissoesDoPerfil)
insert into permissoes (usuario_id, modulo, acao)
select u.id, 'MOVIMENTO', a.acao
from usuarios u
join (values ('ADMIN', 'READ'), ('ADMIN', 'CREATE'), ('ADMIN', 'UPDATE'), ('ADMIN', 'DELETE'),
             ('GESTOR', 'READ'), ('GESTOR', 'CREATE'), ('GESTOR', 'UPDATE'),
             ('USER', 'READ')) as a (role, acao) on a.role = u.role
where not exists (select 1 from permissoes q where q.usuario_id = u.id and q.modulo = 'MOVIMENTO' and q.acao = a.acao);

-- Os módulos que saíram
delete from permissoes where modulo in ('LOCACAO', 'MANUTENCAO');
