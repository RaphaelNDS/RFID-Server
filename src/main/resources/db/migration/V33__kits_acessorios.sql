-- 1.18.0: kits e acessórios da locação. Os acessórios (carregador, bateria, berço, cabo...) não têm etiqueta: são
-- contados. O kit diz quais acessórios acompanham cada equipamento de um tipo (ou de um modelo, que vale antes do
-- kit do tipo). Ao acrescentar uma linha no pedido, o kit entra junto (quantidade do kit x quantidade da linha); o
-- pedido também aceita acessório avulso. Para cada acessório do pedido fica quanto foi pedido, enviado e devolvido.

create table acessorios (
    id         bigint generated by default as identity primary key,
    nome       varchar(120) not null,
    ativo      boolean      not null default true,
    criado_em  timestamp    not null default now()
);
create unique index ux_acessorios_nome on acessorios (lower(nome));

-- modelo_id nulo: o kit do tipo (vale para qualquer marca e modelo do tipo que não tenha kit próprio)
create table kit_itens (
    id                   bigint generated by default as identity primary key,
    tipo_equipamento_id  bigint  not null references tipo_equipamento (id) on delete cascade,
    modelo_id            bigint  references modelo (id) on delete cascade,
    acessorio_id         bigint  not null references acessorios (id),
    quantidade           integer not null,
    constraint ck_kit_itens_quantidade check (quantidade between 1 and 100)
);
create unique index ux_kit_itens on kit_itens (tipo_equipamento_id, coalesce(modelo_id, 0), acessorio_id);

-- linha_id: a linha do pedido que trouxe o acessório pelo kit (nulo: avulso, ou a linha foi removida)
create table pedido_acessorios (
    id              bigint generated by default as identity primary key,
    pedido_id       bigint       not null references pedidos_locacao (id),
    linha_id        bigint       references pedido_linhas (id) on delete set null,
    acessorio_id    bigint       references acessorios (id),
    descricao       varchar(160) not null,
    quantidade      integer      not null,
    enviada         integer      not null default 0,
    devolvida       integer      not null default 0,
    atualizado_em   timestamp,
    atualizado_por  varchar(255),
    constraint ck_pedido_acessorios_quantidade check (quantidade between 1 and 100000),
    constraint ck_pedido_acessorios_enviada check (enviada between 0 and 100000),
    constraint ck_pedido_acessorios_devolvida check (devolvida between 0 and enviada)
);
create index idx_pedido_acessorios_pedido on pedido_acessorios (pedido_id, id);
