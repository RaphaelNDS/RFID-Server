-- 1.23.0: comprovante de entrega do pedido de locação. Na entrega, quem recebe assina na tela (celular ou tablet) e
-- tira-se foto dos equipamentos no local. A assinatura e as fotos ficam no banco, para irem no backup.
create table entregas_pedido (
    id             bigint generated by default as identity primary key,
    pedido_id      bigint        not null references pedidos_locacao (id),
    recebido_por   varchar(160)  not null,
    documento      varchar(40),
    observacao     varchar(500),
    -- Os equipamentos que estavam com o cliente na hora (patrimônio e descrição, um por linha)
    equipamentos   varchar(8000) not null,
    assinatura     bytea         not null,
    registrada_por varchar(255)  not null,
    registrada_em  timestamp     not null default now()
);
create index idx_entregas_pedido on entregas_pedido (pedido_id);

create table entrega_fotos (
    id          bigint generated by default as identity primary key,
    entrega_id  bigint       not null references entregas_pedido (id) on delete cascade,
    tipo        varchar(10)  not null,
    tamanho     integer      not null,
    conteudo    bytea        not null
);
create index idx_entrega_fotos on entrega_fotos (entrega_id);
