-- 1.10.0: empréstimo e devolução de bens, com número (o id), prazo de devolução e termo para assinar.
--
-- Quem recebe é um responsável cadastrado (id para filtrar e o nome no momento, para o termo continuar legível).
-- Cada bem do empréstimo é devolvido sozinho ou junto com os outros (devolvido_em por item); o empréstimo está aberto
-- enquanto algum item não voltou. Na saída o bem fica "Emprestado"; na devolução volta para a situação anterior.
create table emprestimos (
    id                  bigint generated by default as identity primary key,
    responsavel_id      bigint       not null references responsaveis (id),
    responsavel         varchar(255) not null,
    data_saida          date         not null,
    previsao_devolucao  date         not null,
    finalidade          varchar(500),
    registrado_por      varchar(255) not null,
    criado_em           timestamp    not null default now(),
    constraint ck_emprestimos_prazo check (previsao_devolucao >= data_saida)
);
create index idx_emprestimos_saida on emprestimos (data_saida desc, id desc);
create index idx_emprestimos_responsavel on emprestimos (responsavel_id);

-- A etiqueta excluída depois continua no empréstimo (tag_id vira nulo; a etiqueta e o patrimônio ficam).
create table emprestimo_itens (
    id                  bigint generated by default as identity primary key,
    emprestimo_id       bigint       not null references emprestimos (id),
    tag_id              bigint       references tags (id) on delete set null,
    tag_real            varchar(255) not null,
    patrimonio          varchar(255),
    descricao           varchar(255),
    situacao_anterior   varchar(20)  not null,
    devolvido_em        date,
    devolvido_por       varchar(255),
    condicao_devolucao  varchar(500)
);
create index idx_emprestimo_itens_emprestimo on emprestimo_itens (emprestimo_id);
create index idx_emprestimo_itens_tag_real on emprestimo_itens (tag_real);
-- Um bem só pode estar em um empréstimo aberto por vez (duas telas emprestando o mesmo bem ao mesmo tempo)
create unique index ux_emprestimo_itens_aberto on emprestimo_itens (tag_id) where devolvido_em is null and tag_id is not null;
