-- Justificativa dos bens que faltaram num inventário: na finalização, o operador marca no coletor por que cada um
-- não foi encontrado (emprestado, em manutenção, baixado...). Chega depois do inventário finalizado (vai pela fila
-- do app) e aparece no detalhe do inventário na web. Uma por etiqueta e inventário: o reenvio atualiza a mesma.
create table inventario_justificativas (
    id             bigint generated by default as identity primary key,
    inventario_id  varchar(36)  not null,
    tag            varchar(255) not null,
    motivo         varchar(30)  not null,
    observacao     varchar(500),
    operador       varchar(255),
    registrada_em  timestamp    not null,
    constraint fk_justificativas_inventario foreign key (inventario_id) references inventarios (id),
    constraint uk_justificativas_tag unique (inventario_id, tag)
);

-- Itens de inventário por etiqueta: a ficha do bem no coletor (último local em que foi encontrado) e o esperado sem
-- os bens achados depois em outro local procuram a etiqueta em todos os inventários. O índice único (inventario_id,
-- tag) da V3 não serve para isso: começa pelo inventário.
create index if not exists idx_inventario_itens_tag on inventario_itens (tag);
