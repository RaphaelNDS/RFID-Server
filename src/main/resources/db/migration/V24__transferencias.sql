-- 1.6.1: transferência de bens entre locais e responsáveis, com guia numerada (o número é o id).
--
-- O destino guarda o id (para filtrar) e o nome no momento (a guia continua legível se o local ou a pessoa mudar
-- de nome depois). Sem destino de local = só muda o responsável, e vice-versa; ao menos um dos dois é obrigatório.
-- inventario_id: a transferência saiu das divergências de um inventário (bens que faltaram e foram achados noutro lugar).
create table transferencias (
    id                        bigint generated by default as identity primary key,
    data                      date         not null,
    local_destino_id          bigint       references locais (id),
    local_destino             varchar(255),
    responsavel_destino_id    bigint       references responsaveis (id),
    responsavel_destino       varchar(255),
    solicitante               varchar(160),
    motivo                    varchar(500),
    inventario_id             varchar(36),
    registrada_por            varchar(255) not null,
    criada_em                 timestamp    not null default now(),
    constraint ck_transferencias_destino check (local_destino_id is not null or responsavel_destino_id is not null)
);
create index idx_transferencias_data on transferencias (data desc, id desc);

-- Os bens da guia, com a origem de cada um no momento (local e responsável anteriores, pelo nome). A etiqueta
-- excluída depois continua na guia (tag_id vira nulo, a etiqueta e o patrimônio ficam).
create table transferencia_itens (
    id                    bigint generated by default as identity primary key,
    transferencia_id      bigint       not null references transferencias (id),
    tag_id                bigint       references tags (id) on delete set null,
    tag_real              varchar(255) not null,
    patrimonio            varchar(255),
    descricao             varchar(255),
    local_anterior        varchar(255),
    responsavel_anterior  varchar(255)
);
create index idx_transferencia_itens_transferencia on transferencia_itens (transferencia_id);
create index idx_transferencia_itens_tag on transferencia_itens (tag_real);
